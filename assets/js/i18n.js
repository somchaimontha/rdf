function normalizeLang(lang) {
  return lang === 'en' || lang === 'th' ? lang :
    (typeof RDF !== 'undefined' && RDF.DEFAULT_LANG === 'en' ? 'en' : 'th');
}

function readSavedLang() {
  try { return normalizeLang(localStorage.getItem('rdfLang')); }
  catch (_) { return normalizeLang(null); }
}

