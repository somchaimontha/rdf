function t(key) {
  const dictionary = T[normalizeLang(LANG)];
  return Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] :
    (Object.prototype.hasOwnProperty.call(T.th, key) ? T.th[key] : key);
}

function getLocale() { return LANG === 'en' ? 'en-GB' : 'th-TH'; }

// Translate only labels and attributes, never form values or stored codes.
function applyTranslations(root = document) {
  const selector = '[data-t], [data-t-placeholder], [data-t-title], [data-t-aria-label], [data-t-alt]';
  const elements = [...root.querySelectorAll(selector)];
  if (root.matches && root.matches(selector)) elements.unshift(root);
  elements.forEach(el => {
    for (const attr of ['placeholder', 'title', 'aria-label', 'alt']) {
      const key = el.getAttribute('data-t-' + attr);
      if (key && (Object.prototype.hasOwnProperty.call(T.th, key) || Object.prototype.hasOwnProperty.call(T.en, key))) {
        if (el.getAttribute(attr) !== t(key)) el.setAttribute(attr, t(key));
      }
    }
    const key = el.getAttribute('data-t');
    if (!Object.prototype.hasOwnProperty.call(T.th, key) &&
        !Object.prototype.hasOwnProperty.call(T.en, key)) return;
    const attr = el.getAttribute('data-t-attr');
    const value = t(key);
    if (attr) {
      if (el.getAttribute(attr) !== value) el.setAttribute(attr, value);
    } else if (el.textContent !== value) { el.textContent = value; }
  });
}

function setLang(lang) {
  const previousLang = LANG;
  LANG = normalizeLang(lang);
  try { localStorage.setItem('rdfLang', LANG); } catch (_) { /* Session-only preference. */ }
  document.documentElement.lang = LANG;
  applyTranslations();
  const btn = document.getElementById('langBtn');
  if (btn) {
    btn.textContent = LANG === 'th' ? 'EN' : 'TH';
    btn.setAttribute('aria-label', LANG === 'th' ? 'Switch to English' : 'เปลี่ยนเป็นภาษาไทย');
    btn.setAttribute('lang', LANG === 'th' ? 'en' : 'th');
    btn.setAttribute('type', 'button');
  }
  if (previousLang !== LANG) {
    document.dispatchEvent(new CustomEvent('rdf:languagechange', { detail: { lang: LANG, previousLang } }));
  }
}

function toggleLang() { setLang(LANG === 'th' ? 'en' : 'th'); }

document.addEventListener('DOMContentLoaded', () => {
  setLang(LANG);
  // Modal/async renderers can insert translated labels after the initial load.
  // Observe added element subtrees only; text changes made by translation do not loop.
  const observer = new MutationObserver(records => {
    const roots = new Set();
    records.forEach(record => record.addedNodes.forEach(node => {
      if (node.nodeType === 1) roots.add(node);
    }));
    roots.forEach(root => {
      if (!root.isConnected) return;
      for (let parent = root.parentElement; parent; parent = parent.parentElement) {
        if (roots.has(parent)) return;
      }
      applyTranslations(root);
    });
  });
  observer.observe(document.body, { childList: true, subtree: true });
});
